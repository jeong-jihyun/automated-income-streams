"""타로 메이저 아르카나 22장. seed를 주면 같은 결과(시험·재현용)."""
import random

CARDS = [("바보", "새 출발·자유", "무모함·준비 부족"), ("마법사", "의지·실행력", "속임수·재능 낭비"), ("여사제", "직관·고요", "비밀·감춤"),
         ("여황제", "풍요·돌봄", "과잉·의존"), ("황제", "질서·책임", "고집·통제"), ("교황", "전통·조언", "틀에 박힘"),
         ("연인", "선택·관계", "엇갈림·망설임"), ("전차", "추진·승리", "방향 잃음"), ("힘", "용기·인내", "자신감 부족"),
         ("은둔자", "성찰·탐구", "고립"), ("운명의 수레바퀴", "전환점·기회", "정체·타이밍 어긋남"), ("정의", "균형·공정", "편향·불균형"),
         ("매달린 사람", "관점 전환·기다림", "헛된 희생"), ("죽음", "끝과 새 시작(변화)", "변화를 미룸"), ("절제", "조화·절제", "과함·불균형"),
         ("악마", "집착·유혹 알아차림", "벗어남·해방"), ("탑", "갑작스런 변화·깨달음", "변화를 피함"), ("별", "희망·회복", "낙담"),
         ("달", "불안·모호함", "혼란이 걷힘"), ("태양", "활력·성공", "일시적 흐림"), ("심판", "되돌아봄·결단", "자책·미련"), ("세계", "완성·마무리", "마무리 지연")]
POSITIONS = {1: ["지금"], 3: ["과거", "현재", "앞으로의 흐름"]}


def draw(n, seed=None):
    if n not in POSITIONS: raise ValueError("1장 또는 3장만 뽑을 수 있습니다")
    rng = random.Random(seed)
    picks = rng.sample(range(len(CARDS)), n)                       # 중복 없이
    return [{"position": POSITIONS[n][i], "card": CARDS[k][0], "reversed": (rev := rng.random() < 0.5), "meaning": CARDS[k][2] if rev else CARDS[k][1]} for i, k in enumerate(picks)]
