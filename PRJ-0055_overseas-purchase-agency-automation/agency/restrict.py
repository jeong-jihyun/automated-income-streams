"""수입·판매 전에 확인이 필요한 상품 표시. **금지 판정이 아니라 '확인 필요' 안내이며 목록은 예시다.**"""
RULES = [
    ("전기·전자", ["충전기", "어댑터", "보조배터리", "전기", "히터", "블렌더"], "KC 인증 등 전기용품 안전 인증 확인이 필요할 수 있어요"),
    ("어린이용품", ["유아", "아기", "어린이", "장난감", "젖병"], "어린이제품 안전 인증 확인이 필요할 수 있어요"),
    ("식품·건강", ["비타민", "영양제", "건강기능", "프로틴", "식품", "간식"], "식품·건강기능식품은 수입 신고·표시 요건 확인이 필요해요"),
    ("화장품", ["화장품", "크림", "세럼", "립스틱", "선크림"], "화장품은 수입·판매 요건 확인이 필요해요"),
    ("의약품", ["의약품", "약", "연고", "렌즈"], "의료·의약 관련 품목은 판매 제한 가능성이 높아요"),
    ("브랜드·정품", [], "브랜드 상품은 정품 증빙과 상표권 확인이 필요해요"),
]


def check(title, brands=()):
    flags = []
    for name, kws, msg in RULES:
        if name == "브랜드·정품":
            hit = [b for b in brands if b and b.lower() in title.lower()]
            if hit: flags.append({"type": name, "hit": hit, "msg": msg})
        else:
            hit = [k for k in kws if k in title]
            if hit: flags.append({"type": name, "hit": hit, "msg": msg})
    return flags
